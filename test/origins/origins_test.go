// Package origins checks every group's Default flag against the KubeVirt
// release the repository pins.
//
// A group is Default: true if, and only if, KubeVirt does not publish its
// contents. Both directions matter and fail differently:
//
//   - a Default: true group KubeVirt also publishes gives duplicate series,
//     which silently double-counts sum() aggregations
//   - a Default: false group KubeVirt no longer publishes gives a coverage
//     gap, where nobody exports the series at all
//
// Metrics are being moved out of KubeVirt into this controller in stages, so
// each Default flip has to land together with the pin bump for the KubeVirt
// release that drops those metrics. This test is what ties the two together.
package origins

import (
	"bufio"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"testing"

	. "github.com/onsi/ginkgo/v2"
	. "github.com/onsi/gomega"

	"github.com/kubevirt/kubevirt-observability-controller/pkg/monitoring/groups"
	"github.com/kubevirt/kubevirt-observability-controller/pkg/monitoring/selection"
)

const (
	checkoutEnv = "KUBEVIRT_DIR"
	// hack/kubevirt.sh clones the pinned KubeVirt here.
	defaultCheckout = "../../_kubevirt"

	// Generated by KubeVirt's own prom-metrics-collector and kept in sync by
	// its codegen check, so it is authoritative for metrics and recording
	// rules. Reading it beats grepping the sources: names assembled by a
	// helper are present, and names that survive only in a deprecation string
	// are not.
	upstreamMetricsDoc = "docs/observability/metrics.md"

	// Alerts have no generated list upstream, but alert names are always
	// string literals, so the declaration site is reliable.
	upstreamAlertDir = "pkg"

	namespace = "kubevirt"
)

func checkout() string {
	if dir := os.Getenv(checkoutEnv); dir != "" {
		return dir
	}
	return defaultCheckout
}

func TestOrigins(t *testing.T) {
	if _, err := os.Stat(filepath.Join(checkout(), upstreamMetricsDoc)); err != nil {
		t.Skipf("no KubeVirt checkout at %s: run ./hack/kubevirt.sh install (or set %s)",
			checkout(), checkoutEnv)
	}

	RegisterFailHandler(Fail)
	RunSpecs(t, "Origins Suite")
}

var _ = Describe("Group defaults against the pinned KubeVirt", func() {
	var (
		index            selection.Indexes
		upstreamSeries   map[string]bool
		upstreamAlerting map[string]bool
	)

	BeforeEach(func() {
		var err error
		index, err = selection.BuildIndexes(namespace)
		Expect(err).ToNot(HaveOccurred())

		upstreamSeries, err = parseMetricsDoc(filepath.Join(checkout(), upstreamMetricsDoc))
		Expect(err).ToNot(HaveOccurred())
		Expect(upstreamSeries).ToNot(BeEmpty(), "upstream metrics doc parsed to nothing")

		upstreamAlerting, err = parseAlertNames(filepath.Join(checkout(), upstreamAlertDir))
		Expect(err).ToNot(HaveOccurred())
		Expect(upstreamAlerting).ToNot(BeEmpty(), "found no alert declarations upstream")
	})

	series := func(idx selection.Indexes) map[string]groups.Name {
		out := map[string]groups.Name{}
		for name, g := range idx.Metrics {
			out[name] = g
		}
		for name, g := range idx.RecordingRules {
			out[name] = g
		}
		return out
	}

	It("has no default-on metric or recording rule that KubeVirt also publishes", func() {
		found := offenders(series(index), upstreamSeries, true)
		Expect(found).To(BeEmpty(),
			"these are on by default and the pinned KubeVirt publishes them too, so running "+
				"alongside KubeVirt would double-publish them. Set Default: false for the group, "+
				"or bump KUBEVIRT_COMMIT to a release that drops them:\n%s", strings.Join(found, "\n"))
	})

	It("has no default-off metric or recording rule that KubeVirt has stopped publishing", func() {
		found := offenders(series(index), upstreamSeries, false)
		Expect(found).To(BeEmpty(),
			"these are off by default but the pinned KubeVirt no longer publishes them, so nothing "+
				"would export them. Set Default: true for the group:\n%s", strings.Join(found, "\n"))
	})

	It("has no default-on alert that KubeVirt also defines", func() {
		found := offenders(index.Alerts, upstreamAlerting, true)
		Expect(found).To(BeEmpty(),
			"these alerts are on by default and the pinned KubeVirt defines them too. Set "+
				"Default: false for the group, or bump KUBEVIRT_COMMIT:\n%s", strings.Join(found, "\n"))
	})

	It("has no default-off alert that KubeVirt has stopped defining", func() {
		found := offenders(index.Alerts, upstreamAlerting, false)
		Expect(found).To(BeEmpty(),
			"these alerts are off by default but the pinned KubeVirt no longer defines them, so "+
				"nothing would fire them. Set Default: true for the group:\n%s", strings.Join(found, "\n"))
	})
})

// offenders returns every item whose group default disagrees with the pinned
// KubeVirt, as a sorted list.
//
// All of them, not the first: a migration stage flips a whole group at once,
// so violations arrive in batches, and aborting on the first would mean
// fixing them one re-run at a time, in a different order each time.
func offenders(items map[string]groups.Name, upstream map[string]bool, wantOn bool) []string {
	var out []string
	for name, g := range items {
		if defaultOn(g) != wantOn {
			continue
		}
		// On by default and upstream has it: duplicate. Off by default and
		// upstream does not: gap.
		if upstream[name] == wantOn {
			out = append(out, fmt.Sprintf("  %s (group %s)", name, g))
		}
	}
	sort.Strings(out)
	return out
}

func defaultOn(n groups.Name) bool {
	g, ok := groups.Lookup(n)
	return ok && g.Default
}

var docRowPattern = regexp.MustCompile(`^\|\s*([a-zA-Z_:0-9]+)\s*\|`)

// parseMetricsDoc reads the names out of KubeVirt's generated metrics table.
func parseMetricsDoc(path string) (map[string]bool, error) {
	f, err := os.Open(path) //nolint:gosec // path is the pinned checkout
	if err != nil {
		return nil, err
	}
	defer f.Close() //nolint:errcheck // read-only

	out := map[string]bool{}
	scanner := bufio.NewScanner(f)
	for scanner.Scan() {
		m := docRowPattern.FindStringSubmatch(scanner.Text())
		if m != nil && m[1] != "Name" {
			out[m[1]] = true
		}
	}
	return out, scanner.Err()
}

var alertPattern = regexp.MustCompile(`Alert:\s*"([A-Za-z]+)"`)

// parseAlertNames collects the alert names KubeVirt declares.
func parseAlertNames(root string) (map[string]bool, error) {
	out := map[string]bool{}
	err := filepath.WalkDir(root, func(path string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() || !strings.HasSuffix(path, ".go") {
			return nil //nolint:nilerr // a missing subtree is not fatal
		}
		data, readErr := os.ReadFile(path) //nolint:gosec // paths come from the walk
		if readErr != nil {
			return readErr
		}
		for _, m := range alertPattern.FindAllStringSubmatch(string(data), -1) {
			out[m[1]] = true
		}
		return nil
	})
	return out, err
}
